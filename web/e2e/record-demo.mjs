async function caption(title, text, seconds) {
  step++;
  await page.evaluate(({ title, text, step }) => {
    let panel = document.getElementById('walkthrough-caption');
    if (!panel) {
      panel = document.createElement('aside'); panel.id = 'walkthrough-caption';
      panel.style.cssText = 'position:fixed;bottom:12px;left:12px;right:12px;z-index:9999;background:#073e46;color:white;border-radius:8px;padding:18px 22px;font:16px/1.6 system-ui;box-shadow:0 3px 18px #0003';
      document.body.append(panel);
    }
    panel.replaceChildren();
    const label = document.createElement('div'); label.style.cssText = 'font-size:12px;color:#ffd36e;margin-bottom:5px;font-weight:600';
    label.textContent = `Synthetic data / recorded local application / ${String(step).padStart(2, '0')} / ${title}`;
    const body = document.createElement('p'); body.textContent = text;
    panel.append(label, body);
  }, { title, text, step });
  await page.waitForTimeout(seconds * 1000);
}
