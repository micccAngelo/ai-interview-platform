import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const demo = JSON.parse(await fs.readFile('../api/tmp/evidence-demo.json', 'utf8'));
const headers = { Authorization: `Bearer ${demo.token}` };
const base = 'http://127.0.0.1:3001/api/v1';
const response = await fetch(`${base}/sessions/${demo.session_id}/portfolio`, { headers });
assert.equal(response.status, 200);
const { portfolio } = await response.json();
assert.equal(portfolio.skills.length, 4);
assert.equal(portfolio.skills.filter((row) => row.assessment_status === 'assessed').length, 2);
assert.equal(portfolio.skills.filter((row) => row.ai_level === null).length, 2);
const comparisonResponse = await fetch(`${base}/portfolios/${demo.portfolio_id}/fitgap/${demo.vacancy_id}`, { headers });
assert.equal(comparisonResponse.status, 200);
const { report } = await comparisonResponse.json();
assert.equal(report.skill_comparisons.find((row) => row.skill_id === 'sql').result, 'not_assessed');
assert.equal(report.skill_comparisons.find((row) => row.skill_id === 'sql').expected_level, 4);
assert.equal(report.culture_narrative, null);
const pdfResponse = await fetch(`${base}/portfolios/${demo.portfolio_id}/export?format=pdf&vacancy_id=${demo.vacancy_id}`, { headers });
assert.equal(pdfResponse.status, 200);
const pdf = Buffer.from(await pdfResponse.arrayBuffer()); assert.equal(pdf.subarray(0, 4).toString(), '%PDF');
await fs.writeFile('../assessment/sample-portfolio.pdf', pdf);
const jsonResponse = await fetch(`${base}/portfolios/${demo.portfolio_id}/export?format=json`, { headers });
assert.equal(jsonResponse.status, 200);
await fs.writeFile('../assessment/sample-export.json', JSON.stringify(await jsonResponse.json(), null, 2));
console.log('PASS: live Rails API returns 4 skills, 2 assessed and 2 null ratings. SQL remains not_assessed with expected_level=4. Real JSON and PDF exports saved. No model provider was called.');
